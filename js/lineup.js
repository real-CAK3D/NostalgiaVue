export function buildLineup() {
  const all = [
    ...localMediaChannels(),
    { n: 3, cat: 'GAMES', call: 'GAME', name: 'Game Channel', kind: 'games' },
    ...areaChannels(),
    ...NOSTALGIA, ...YOUTUBE, ...PODCASTS, ...MORE, ...PPV, ...PLAYLISTS, ...LIVE_247, ...SHOWS, ...MORE_SHOWS, ...EXTRA,
  ];
  const taken = new Map(all.map(c => [c.n, c]));
  for (const u of settings.userChannels) {
    const ch = { ...u, user: true };
    if (taken.has(u.n)) all.splice(all.indexOf(taken.get(u.n)), 1, ch); else all.push(ch);
    taken.set(u.n, ch);
  }
  for (let i = 0; i < all.length; i++) {
    const c = all[i], qs = YTS[c.n];
    if (qs && !c.user) all[i] = { ...c, kind: 'yt', yt: c.yt || [], search: { q: qs }, q: c.q || [] };
  }
  const names = settings.ytNames || {};
  for (let i = 0; i < all.length; i++) {
    const c = all[i];
    if (c.autoName && c.yt && names[c.yt[0]]) all[i] = { ...c, name: names[c.yt[0]] };
  }
  // LIVE twins: every channel built on a YouTube channel ID gets a live slot from 700 up
  const taken2 = new Set(all.map(c => c.n));
  let ln = 700;
  for (const c of [...all].sort((x, y) => x.n - y.n)) {
    const id = c.kind === 'yt' && !c.mix && c.yt && c.yt.find(x => x.startsWith('UC'));
    if (!id || c.n >= 700) continue;
    while (taken2.has(ln) && ln < 780) ln++;
    if (ln >= 780) break;
    all.push({ n: ln, cat: 'LIVE', call: c.call, name: `${c.name} · LIVE`, kind: 'ytlive', channelId: id, from: c.n, desc: `Whatever ${c.name} is streaming live right now. Press OK to watch its latest videos on ${c.n} instead.` });
    taken2.add(ln++);
  }
  all.sort((x, y) => x.n - y.n);
  CHANNELS = all;
  return all;
}
export const chanByNum = n => CHANNELS.find(c => c.n === n);
// Kids profile: only these categories (and the weather, guide and game channels) are shown.
export const KIDS_CATS = new Set(['KIDS', 'CARTOONS', 'LEARNING', 'NATURE', 'SCIENCE', 'GAMES', 'GUIDE', 'SEASONAL', 'COZY']);
const KIDS_KINDS = new Set(['weather', 'guidech', 'games']);
export const kidsHidden = ch => !!(ch && settings.kids && !KIDS_CATS.has(ch.cat) && !KIDS_KINDS.has(ch.kind));
export const isHidden = n => settings.hidden.includes(n) || kidsHidden(chanByNum(n));
export const surfable = () => CHANNELS.filter(c => !isHidden(c.n));

export function nextFree(sectionId) {
  const s = SECTIONS.find(x => x.id === sectionId);
  for (let n = s.from; n <= s.to; n++) if (!chanByNum(n)) return n;
  return null;
}
// Call letters for a user channel: initials or first letters, max 4.
export function makeCall(name) {
  const w = String(name).toUpperCase().replace(/[^A-Z0-9 ]/g, ' ').split(/\s+/).filter(Boolean);
  if (!w.length) return 'CH';
  return (w.length > 1 ? w.map(x => x[0]).join('') : w[0]).slice(0, 4);
}
